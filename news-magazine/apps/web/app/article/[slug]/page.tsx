type Props2 = { params: Promise<{ slug: string }> };

/**
 * Only YouTube/Vimeo URLs are embedded in an iframe. The ingestion
 * worker stores whatever og:video pointed at, so an arbitrary value
 * rendered into iframe src would be an injection vector.
 */
function embeddableVideo(url: string | null): string | null {
  if (!url) return null;
  try {
    const parsed = new URL(url);
    const host = parsed.hostname.replace(/^www\./, "");
    if (host === "youtube.com" || host === "youtube-nocookie.com" || host === "youtu.be") {
      const id =
        host === "youtu.be"
          ? parsed.pathname.slice(1)
          : (parsed.searchParams.get("v") ??
            parsed.pathname.split("/").filter(Boolean).pop() ??
            "");
      return id ? `https://www.youtube-nocookie.com/embed/${id}` : null;
    }
    if (host === "player.vimeo.com") return url;
  } catch {
    return null;
  }
  return null;
}

export async function generateMetadata({ params }: Props2): Promise<Metadata> {
  const { slug } = await params;
  const article = await getArticleBySlug(slug);

  if (!article) {
    return { title: "Article not found" };
  }

  const image = article.image_highres_url ?? article.featured_image_url ?? undefined;
  const description = clampDescription(article.excerpt ?? article.subtitle);
  const url = `${SITE_URL}/article/${article.slug}`;

  return {
    // No site-name suffix here. layout.tsx declares
    // title.template = "%s | Nepal News & Magazine", so appending it
    // again produced "Headline | Nepal News & Magazine | Nepal News &
    // Magazine" in every indexable title on the site.
    title: article.headline,
    description: description || undefined,
    alternates: { canonical: url },
    openGraph: {
      title: article.headline,
      description: description || undefined,
      type: "article",
      url,
      siteName: SITE_NAME,
      locale: article.language === "en" ? "en_US" : "ne_NP",
      publishedTime: article.published_at ?? undefined,
      modifiedTime: article.updated_at ?? article.published_at ?? undefined,
      authors: article.source_name_snapshot
        ? [article.source_name_snapshot]
        : undefined,
      images: image
        ? [{ url: image, width: 1200, height: 630, alt: article.headline }]
        : [{ url: SITE_LOGO, width: 192, height: 192, alt: SITE_NAME }],
    },
    twitter: {
      card: "summary_large_image",
      title: article.headline,
      description: description || undefined,
      images: image ? [image] : [SITE_LOGO],
    },
  };
}

/**
 * Article page.
 *
 * Stage 1 special-cased any slug starting with "live-" and rendered
 * <LiveArticleClient>, which looked the id up in the /api/live-news
 * response. That endpoint regenerated its ids on every call, so those
 * links 404'd or hung on "Loading..." forever. Gemini's ids
 * (`gemini-live-0-<timestamp>`) did not even match the "live-" guard, so
 * every card generated by the live feed linked to a dead page.
 *
 * It also called increment_article_view from the render body, which runs
 * on every request including the client-side navigation prefetch —
 * inflating the counter roughly 4,800x/day.
 */
export default async function ArticlePage({ params }: Props) {
  const { slug } = await params;

  const article = await getArticleBySlug(slug);
  if (!article) notFound();

  const [categories, relatedArticles] = await Promise.all([
    getCategories(),
    getRelatedArticles(article.primary_category_id, article.id, 4),
  ]);

  const category = categories.find((item) => item.id === article.primary_category_id);
  const categoryName = category ? (category.name_ne ?? category.name_en) : null;

  const points = (article.summary_points as string[] | null) ?? [];
  const image =
    article.image_highres_url ?? article.featured_image_url ?? article.gif_url ?? null;
  const embed = embeddableVideo(article.video_embed_url ?? article.video_url);

  const articleUrl = `${SITE_URL}/article/${article.slug}`;
  const description = clampDescription(article.excerpt ?? article.subtitle);

  const structuredData = {
    "@context": "https://schema.org",
    "@type": "NewsArticle",
    headline: article.headline,
    description: description || undefined,
    datePublished: article.published_at ?? undefined,
    dateModified: article.updated_at ?? article.published_at ?? undefined,
    url: articleUrl,
    mainEntityOfPage: {
      "@type": "WebPage",
      // Absolute, and pointing at THIS site.
      //
      // It used to be `article.canonical_url ?? "/article/<slug>"`, and
      // canonical_url holds the *originating outlet's* address — so a
      // story from kathmandupost.com declared its canonical to be
      // kathmandupost.com. That tells search engines this page is a
      // duplicate of the original and drops it from the index. The
      // fallback was a relative path, which is not a resolvable IRI.
      "@id": articleUrl,
    },
    image: image ? [image] : [SITE_LOGO],
    // This page is published by the site operator.
    //
    // publisher used to be set to source_name_snapshot, i.e. the third-
    // party outlet the story came from. Declaring someone else's name
    // as the publisher of a page they do not own is publisher
    // impersonation in structured data, and it had no logo, which is
    // what Google checks first for News eligibility.
    publisher: {
      "@type": "NewsMediaOrganization",
      name: SITE_NAME,
      url: SITE_URL,
      logo: {
        "@type": "ImageObject",
        // 192px, not app/icon.svg: Google's publisher-logo guidance
        // requires at least 112x112 and that SVG's viewBox is 64x64.
        url: SITE_LOGO,
        width: 192,
        height: 192,
      },
    },
    // Credit the outlet that actually filed the story.
    author: article.source_name_snapshot
      ? {
          "@type": "Organization",
          name: article.source_name_snapshot,
          url: article.source_article_url ?? undefined,
        }
      : undefined,
    isBasedOn: article.source_article_url ?? undefined,
    inLanguage: article.language === "en" ? "en" : "ne",
    articleSection: category?.name_en ?? undefined,
    wordCount: article.word_count ?? undefined,
  };

  const breadcrumbData = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: SITE_URL },
      ...(category
        ? [
            {
              "@type": "ListItem",
              position: 2,
              name: category.name_en,
              item: `${SITE_URL}/category/${category.slug}`,
            },
          ]
        : []),
      { "@type": "ListItem", position: category ? 3 : 2, name: article.headline, item: articleUrl },
    ],
  };

  return (
    <>
      {/* jsonLd() escapes `<`, so a headline containing `</script>`
          cannot close this element and inject markup. */}
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: jsonLd(structuredData) }}
      />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: jsonLd(breadcrumbData) }}
      />

      {/* One view per page view, not per render. */}
      <ArticleViewTracker articleId={article.id} />

      <main className="mx-auto max-w-3xl px-4 py-8 md:py-12">
        <article>
          {category && (
            <div className="mb-4">
              <Link
                href={`/category/${category.slug}`}
                className="text-sm font-semibold uppercase tracking-wide text-blue-600 hover:underline"
              >
                {categoryName}
              </Link>
            </div>
          )}

          <h1 className="font-headline text-3xl font-bold leading-tight text-gray-900 md:text-4xl">
            {article.headline}
          </h1>

          <div className="mt-5 flex flex-wrap items-center gap-x-4 gap-y-2 border-b pb-5 text-sm text-gray-500">
            {article.source_name_snapshot && (
              <span>
                Source:{" "}
                <strong className="text-gray-700">{article.source_name_snapshot}</strong>
              </span>
            )}
            {Number(article.source_count ?? 1) > 1 && (
              <span className="rounded bg-emerald-50 px-2 py-0.5 text-xs font-semibold text-emerald-700">
                Also reported by {Number(article.source_count) - 1} other
                {Number(article.source_count) - 1 === 1 ? "" : "s"}
              </span>
            )}
            {article.published_at && (
              <time dateTime={article.published_at}>{formatNewsDate(article.published_at)}</time>
            )}
          </div>

          {/* The four points, extracted verbatim from the article.

              Dark variants throughout: this panel had a fixed
              `bg-blue-50/60` with no `dark:` pair, so in dark mode a
              pale blue card sat on a near-black page behind light
              text — unreadable. */}
          {points.length > 0 && (
            <section className="mt-6 rounded-lg border border-blue-100 bg-blue-50/60 p-5 dark:border-blue-900/60 dark:bg-blue-950/40">
              <h2 className="text-xs font-bold uppercase tracking-wider text-blue-700 dark:text-blue-300">
                In this story
              </h2>
              <TranslatePoints
                points={points}
                language={article.language}
                translated={article.summary_points_translated ?? null}
              />
            </section>
          )}

          {embed && (
            <div className="mt-6 aspect-video w-full overflow-hidden rounded-xl bg-black">
              <iframe
                src={embed}
                title={article.headline}
                className="h-full w-full"
                allow="accelerometer; clipboard-write; encrypted-media; picture-in-picture"
                allowFullScreen
              />
            </div>
          )}

          {!embed && image && (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={image}
              alt={article.featured_image_alt ?? article.headline}
              className="mt-6 aspect-video w-full rounded-xl object-cover"
            />
          )}

          <ArticleMedia
            audioUrl={article.audio_url}
            videoUrl={article.video_embed_url ?? article.video_url}
            hasEmbed={Boolean(embed)}
          />

          {(article.excerpt || points.length === 0) && article.excerpt && (
            <p className="mt-6 text-lg leading-8 text-gray-800">{article.excerpt}</p>
          )}

          {points.length === 0 && !article.excerpt && (
            <p className="mt-6 text-sm text-gray-500">
              No summary is available for this story. Read the full report at the
              original source.
            </p>
          )}

          {/* The full article lives on the outlet's own site. */}
          {article.source_article_url && (
            <a
              href={article.source_article_url}
              target="_blank"
              rel="noopener noreferrer nofollow"
              className="mt-8 flex items-center justify-between rounded-lg border-2 border-blue-600 bg-blue-50 px-5 py-4 font-semibold text-blue-800 transition hover:bg-blue-100 dark:border-blue-500 dark:bg-blue-950/50 dark:text-blue-200 dark:hover:bg-blue-900/50"
            >
              <span>
                Read the full story on{" "}
                {article.source_name_snapshot ?? "the original source"} ↗
              </span>
            </a>
          )}

          <div className="mt-6">
            <ShareButtons url={`/article/${article.slug}`} title={article.headline} />
          </div>
        </article>

        {relatedArticles.length > 0 && (
          <aside className="mt-14 border-t pt-8">
            <h2 className="mb-5 text-xl font-bold text-gray-900">Related coverage</h2>
            <div className="grid gap-5 sm:grid-cols-2">
              {relatedArticles.map((related) => (
                <Link
                  key={related.id}
                  href={`/article/${related.slug}`}
                  className="group block rounded-lg border border-gray-200 bg-white p-4 transition hover:border-gray-400 dark:border-gray-700 dark:bg-gray-900 dark:hover:border-gray-500"
                >
                  <h3 className="font-semibold leading-snug text-gray-900 group-hover:text-blue-700">
                    {related.headline}
                  </h3>
                  <p className="mt-1.5 line-clamp-2 text-sm text-gray-600">
                    {related.summary_points?.[0] ?? related.excerpt ?? ""}
                  </p>
                  <p className="mt-2 text-xs text-gray-400">
                    {related.source_name_snapshot ?? ""}
                  </p>
                </Link>
              ))}
            </div>
          </aside>
        )}
      </main>
    </>
  );
}