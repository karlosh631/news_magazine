/**
 * Only YouTube/Vimeo URLs are embedded in an iframe. The ingestion
 * worker stores whatever og:video pointed at, so an arbitrary value
 * rendered into iframe src would be an injection vector.
 */
function embeddableVideo(url: string | null): string | null {
  if (!url) return null;
  try {
    const parsed = new URL(url);
    const host = parsed.hostname.replace(/^www\./, "");
    if (host === "youtube.com" || host === "youtube-nocookie.com" || host === "youtu.be") {
      const id =
        host === "youtu.be"
          ? parsed.pathname.slice(1)
          : (parsed.searchParams.get("v") ??
            parsed.pathname.split("/").filter(Boolean).pop() ??
            "");
      return id ? `https://www.youtube-nocookie.com/embed/${id}` : null;
    }
    if (host === "player.vimeo.com") return url;
  } catch {
    return null;
  }
  return null;
}

export async function generateMetadata({ params }: Props2): Promise<Metadata> {
  const { slug } = await params;
  const article = await getArticleBySlug(slug);

  if (!article) {
    return { title: "Article not found | Nepal News & Magazine" };
  }

  const image = article.image_highres_url ?? article.featured_image_url ?? undefined;
  const description = article.excerpt ?? article.subtitle ?? undefined;

  return {
    title: `${article.headline} | Nepal News & Magazine`,
    description,
    openGraph: {
      title: article.headline,
      description,
      type: "article",
      publishedTime: article.published_at ?? undefined,
      images: image ? [{ url: image }] : undefined,
    },
    twitter: {
      card: image ? "summary_large_image" : "summary",
      title: article.headline,
      description,
      images: image ? [image] : undefined,
    },
  };
}

/**
 * Article page.
 *
 * Stage 1 special-cased any slug starting with "live-" and rendered
 * <LiveArticleClient>, which looked the id up in the /api/live-news
 * response. That endpoint regenerated its ids on every call, so those
 * links 404'd or hung on "Loading..." forever. Gemini's ids
 * (`gemini-live-0-<timestamp>`) did not even match the "live-" guard, so
 * every card generated by the live feed linked to a dead page.
 *
 * It also called increment_article_view from the render body, which runs
 * on every request including the client-side navigation prefetch —
 * inflating the counter roughly 4,800x/day.
 */
export default async function ArticlePage({ params }: Props) {
  const { slug } = await params;

  const article = await getArticleBySlug(slug);
  if (!article) notFound();

  const [categories, relatedArticles] = await Promise.all([
    getCategories(),
    getRelatedArticles(article.primary_category_id, article.id, 4),
  ]);

  const category = categories.find((item) => item.id === article.primary_category_id);
  const categoryName = category ? (category.name_ne ?? category.name_en) : null;

  const points = (article.summary_points as string[] | null) ?? [];
  const image =
    article.image_highres_url ?? article.featured_image_url ?? article.gif_url ?? null;
  const embed = embeddableVideo(article.video_embed_url ?? article.video_url);

  const structuredData = {
    "@context": "https://schema.org",
    "@type": "NewsArticle",
    headline: article.headline,
    description: article.excerpt ?? article.subtitle ?? undefined,
    datePublished: article.published_at ?? undefined,
    dateModified: article.updated_at ?? article.published_at ?? undefined,
    image: image ? [image] : undefined,
    mainEntityOfPage: {
      "@type": "WebPage",
      "@id": article.canonical_url ?? `/article/${article.slug}`,
    },
    publisher: { "@type": "Organization", name: article.source_name_snapshot ?? "Nepal News & Magazine" },
  };

  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(structuredData) }}
      />

      {/* One view per page view, not per render. */}
      <ArticleViewTracker articleId={article.id} />

      <main className="mx-auto max-w-3xl px-4 py-8 md:py-12">
        <article>
          {category && (
            <div className="mb-4">
              <Link
                href={`/category/${category.slug}`}
                className="text-sm font-semibold uppercase tracking-wide text-blue-600 hover:underline"
              >
                {categoryName}
              </Link>
            </div>
          )}

          <h1 className="font-headline text-3xl font-bold leading-tight text-gray-900 md:text-4xl">
            {article.headline}
          </h1>

          <div className="mt-5 flex flex-wrap items-center gap-x-4 gap-y-2 border-b pb-5 text-sm text-gray-500">
            {article.source_name_snapshot && (
              <span>
                Source:{" "}
                <strong className="text-gray-700">{article.source_name_snapshot}</strong>
              </span>
            )}
            {Number(article.source_count ?? 1) > 1 && (
              <span className="rounded bg-emerald-50 px-2 py-0.5 text-xs font-semibold text-emerald-700">
                Also reported by {Number(article.source_count) - 1} other
                {Number(article.source_count) - 1 === 1 ? "" : "s"}
              </span>
            )}
            {article.published_at && (
              <time dateTime={article.published_at}>{formatNewsDate(article.published_at)}</time>
            )}
          </div>

          {/* The four points, extracted verbatim from the article. */}
          {points.length > 0 && (
            <section className="mt-6 rounded-lg border border-blue-100 bg-blue-50/60 p-5">
              <h2 className="text-xs font-bold uppercase tracking-wider text-blue-700">
                In this story
              </h2>
              <SummaryPoints points={points} />
            </section>
          )}

          {embed && (
            <div className="mt-6 aspect-video w-full overflow-hidden rounded-xl bg-black">
              <iframe
                src={embed}
                title={article.headline}
                className="h-full w-full"
                allow="accelerometer; clipboard-write; encrypted-media; picture-in-picture"
                allowFullScreen
              />
            </div>
          )}

          {!embed && image && (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={image}
              alt={article.featured_image_alt ?? article.headline}
              className="mt-6 aspect-video w-full rounded-xl object-cover"
            />
          )}

          <ArticleMedia
            audioUrl={article.audio_url}
            videoUrl={article.video_embed_url ?? article.video_url}
            hasEmbed={Boolean(embed)}
          />

          {(article.excerpt || points.length === 0) && article.excerpt && (
            <p className="mt-6 text-lg leading-8 text-gray-800">{article.excerpt}</p>
          )}

          {points.length === 0 && !article.excerpt && (
            <p className="mt-6 text-sm text-gray-500">
              No summary is available for this story. Read the full report at the
              original source.
            </p>
          )}

          {/* The full article lives on the outlet's own site. */}
          {article.source_article_url && (
            <a
              href={article.source_article_url}
              target="_blank"
              rel="noopener noreferrer nofollow"
              className="mt-8 flex items-center justify-between rounded-lg border-2 border-blue-600 bg-blue-50 px-5 py-4 font-semibold text-blue-800 transition hover:bg-blue-100"
            >
              <span>
                Read the full story on{" "}
                {article.source_name_snapshot ?? "the original source"} ↗
              </span>
            </a>
          )}

          <div className="mt-6">
            <ShareButtons url={`/article/${article.slug}`} title={article.headline} />
          </div>
        </article>

        {relatedArticles.length > 0 && (
          <aside className="mt-14 border-t pt-8">
            <h2 className="mb-5 text-xl font-bold text-gray-900">Related coverage</h2>
            <div className="grid gap-5 sm:grid-cols-2">
              {relatedArticles.map((related) => (
                <Link
                  key={related.id}
                  href={`/article/${related.slug}`}
                  className="group block rounded-lg border border-gray-200 bg-white p-4 transition hover:border-gray-400"
                >
                  <h3 className="font-semibold leading-snug text-gray-900 group-hover:text-blue-700">
                    {related.headline}
                  </h3>
                  <p className="mt-1.5 line-clamp-2 text-sm text-gray-600">
                    {related.summary_points?.[0] ?? related.excerpt ?? ""}
                  </p>
                  <p className="mt-2 text-xs text-gray-400">
                    {related.source_name_snapshot ?? ""}
                  </p>
                </Link>
              ))}
            </div>
          </aside>
        )}
      </main>
    </>
  );
}